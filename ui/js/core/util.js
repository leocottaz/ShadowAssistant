function icon(name, cls = '') {
  return `<svg class="ic ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ''}</svg>`;
}
function hydrateIcons(root = document) {
  $$('i[data-icon]', root).forEach((i) => { i.outerHTML = icon(i.dataset.icon, i.className); });
}

const store = {
  get(key, fallback) {
    try {
      const v = localStorage.getItem('shadow.' + key);
      return v == null ? fallback : JSON.parse(v);
    } catch { return fallback; }
  },
  set(key, value) {
    try { localStorage.setItem('shadow.' + key, JSON.stringify(value)); } catch { /* quota ou stockage indisponible */ }
  },
};

let toastTimer;
function toast(text) {
  const t = $('#toast');
  t.textContent = text;
  t.classList.add('show');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.classList.remove('show'), 2400);
}

function autosize(t, max = 400) {
  t.style.height = 'auto';
  t.style.height = Math.min(t.scrollHeight, max) + 'px';
}

function animateOut(el, done) {
  if (!el || document.body.classList.contains('reduce')) { done(); return; }
  el.classList.add('leaving');
  setTimeout(done, 340);
}

